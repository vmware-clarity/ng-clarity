// Writes each AI context JSON Schema as a file, the contract a backend validates with, and compiles it into a
// standalone validator for the library, so the page validates with the same schema without shipping Ajv.
// A schema version is locked by its hash: changing a released schema without a new version fails.
// Usage: node scripts/ai-schemas.js [--check]

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const Ajv = require('ajv/dist/2020').default;
const standaloneCode = require('ajv/dist/standalone').default;

const DIR = 'projects/angular/ai/contextual/schemas';
const SCHEMAS = [
  {
    name: 'page-context',
    source: 'projects/angular/ai/contextual/schema.ts',
    schema: 'CLR_PAGE_CONTEXT_SCHEMA',
    version: 'CLR_PAGE_CONTEXT_SCHEMA_VERSION',
  },
];
const LOCK = path.join(DIR, 'versions.json');
const HEADER = `/*
 * Copyright (c) 2016-2026 Broadcom. All Rights Reserved.
 * The term "Broadcom" refers to Broadcom Inc. and/or its subsidiaries.
 * This software is released under MIT license.
 * The full license information can be found in LICENSE in the root directory of this project.
 */

// Generated by scripts/ai-schemas.js from the schema; do not edit.
// @ts-nocheck
`;

async function main() {
  const check = process.argv.includes('--check');
  const lock = fs.existsSync(LOCK) ? JSON.parse(fs.readFileSync(LOCK, 'utf8')) : {};
  const expected = new Map();
  const problems = [];

  for (const entry of SCHEMAS) {
    const module = await import(path.resolve(entry.source));
    const schema = module[entry.schema];
    const version = module[entry.version];
    const json = JSON.stringify(schema, null, 2) + '\n';
    const hash = crypto.createHash('sha256').update(json).digest('hex');

    const locked = lock[entry.name]?.[version];
    if (locked && locked !== hash) {
      problems.push(`${entry.name} ${version} changed after it was locked: give the changed schema a new version.`);
    }
    lock[entry.name] = { ...lock[entry.name], [version]: hash };

    const ajv = new Ajv({ code: { source: true, esm: true } });
    const code = standaloneCode(ajv, ajv.compile(schema));
    expected.set(path.join(DIR, `${entry.name}-${version}.schema.json`), json);
    expected.set(path.join(DIR, `${entry.name}.validator.ts`), HEADER + code + '\n');
  }
  expected.set(LOCK, JSON.stringify(lock, null, 2) + '\n');

  for (const [file, content] of expected) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === content) {
      continue;
    }
    if (check) {
      problems.push(`${file} is out of date: run npm run ai-schemas:update.`);
    } else if (!problems.length) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
      console.log(`Wrote ${file}`);
    }
  }

  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
