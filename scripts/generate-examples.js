/**
 * Generates the code that the website, the demo app and Storybook use to consume the shared examples in
 * projects/examples. For every component folder that has an examples.json, it writes:
 *
 * - projects/examples/<component>/index.ts: every example with its component, metadata and source text.
 * - .storybook/stories/examples/<component>.stories.ts: one story per example that targets Storybook.
 *
 * Run with --check to fail when a generated file is out of date instead of writing it.
 */

const fs = require('fs');
const glob = require('glob');
const path = require('path');
const prettier = require('prettier');

const prettierConfig = require('../.prettierrc.js');

const ROOT = path.resolve(__dirname, '..');
const EXAMPLES_ROOT = path.join(ROOT, 'projects/examples');
const STORIES_ROOT = path.join(ROOT, '.storybook/stories/examples');
const TARGETS = ['website', 'demo', 'storybook'];

const TS_LICENSE_HEADER = fs.readFileSync(path.join(ROOT, '.license-header.js')).toString().trim();
const HTML_LICENSE_HEADER = fs.readFileSync(path.join(ROOT, '.license-header.html')).toString().trim();
const GENERATED_NOTICE =
  '// Generated by scripts/generate-examples.js from examples.json. Do not edit; run `npm run examples:generate`.';

const check = process.argv.includes('--check');

main().catch(error => {
  console.error(error.message);
  process.exit(1);
});

async function main() {
  const outputs = new Map();

  for (const manifestPath of glob.sync('*/examples.json', { cwd: EXAMPLES_ROOT }).sort()) {
    const name = path.dirname(manifestPath);
    const manifest = JSON.parse(fs.readFileSync(path.join(EXAMPLES_ROOT, manifestPath)).toString());
    const examples = manifest.examples.map(example => readExample(name, example));

    outputs.set(path.join(EXAMPLES_ROOT, name, 'index.ts'), await format(buildIndex(name, examples), 'index.ts'));

    if (examples.some(example => example.targets.includes('storybook'))) {
      const storiesPath = path.join(STORIES_ROOT, `${name}.stories.ts`);
      outputs.set(storiesPath, await format(buildStories(name, manifest.title, examples), storiesPath));
    }
  }

  // Stories of components that no longer have Storybook examples.
  const staleStories = glob
    .sync('*.stories.ts', { cwd: STORIES_ROOT, absolute: true })
    .map(filePath => path.normalize(filePath))
    .filter(filePath => !outputs.has(filePath));

  const outdated = [...outputs].filter(([filePath, code]) => readFile(filePath) !== code);

  if (check) {
    for (const filePath of [...outdated.map(([filePath]) => filePath), ...staleStories]) {
      console.error(`${path.relative(ROOT, filePath)} is out of date. Run \`npm run examples:generate\`.`);
    }
    process.exit(outdated.length || staleStories.length ? 1 : 0);
  }

  for (const [filePath, code] of outdated) {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, code);
  }
  for (const filePath of staleStories) {
    fs.unlinkSync(filePath);
  }
}

function readExample(name, { id, title, targets, showStyles = true }) {
  const unknownTargets = targets.filter(target => !TARGETS.includes(target));
  if (unknownTargets.length) {
    throw new Error(`${name}/${id}: unknown targets ${unknownTargets.join(', ')}. Use ${TARGETS.join(', ')}.`);
  }

  const basePath = path.join(EXAMPLES_ROOT, name, `${id}.example`);
  const ts = readFile(`${basePath}.ts`);
  const html = readFile(`${basePath}.html`);
  const scss = readFile(`${basePath}.scss`);

  if (ts === undefined || html === undefined) {
    throw new Error(`${name}/${id}: expected ${id}.example.ts and ${id}.example.html next to examples.json.`);
  }

  const className = ts.match(/export class (\w+)/)?.[1];
  if (!className) {
    throw new Error(`${name}/${id}: ${id}.example.ts does not export a component class.`);
  }

  return {
    id,
    key: camelCase(id),
    title,
    targets,
    showStyles,
    className,
    source: {
      html: stripLicenseHeader(html),
      ts: toStackBlitzComponent(stripLicenseHeader(ts), id, className),
      scss: scss === undefined ? undefined : stripLicenseHeader(scss),
      hasLogic: !new RegExp(`export class ${className} \\{\\}`).test(ts),
    },
  };
}

/**
 * Renames the component and its files to what the website's StackBlitz project expects
 * (projects/website/stackblitz-example-template), so that the shown code can be copied as is.
 */
function toStackBlitzComponent(ts, id, className) {
  return ts
    .replace(new RegExp(`\\b${className}\\b`, 'g'), 'ExampleComponent')
    .replace(/selector: '[^']*'/, "selector: 'app-example'")
    .replace(`'./${id}.example.html'`, "'./example.component.html'")
    .replace(`'./${id}.example.scss'`, "'./example.component.scss'");
}

function buildIndex(name, examples) {
  const imports = examples
    .map(example => `import { ${example.className} } from './${example.id}.example';`)
    .sort((a, b) => a.split("'")[1].localeCompare(b.split("'")[1]));

  const entries = examples.map(
    example => `${example.key}: {
      id: ${JSON.stringify(`${name}/${example.id}`)},
      title: ${JSON.stringify(example.title)},
      targets: ${JSON.stringify(example.targets)},
      component: ${example.className},
      showStyles: ${example.showStyles},
      source: ${JSON.stringify(example.source)},
    },`
  );

  return `${TS_LICENSE_HEADER}

${GENERATED_NOTICE}

import { Example } from '../example';
${imports.join('\n')}

export const ${constantName(name)} = {
  ${entries.join('\n')}
} satisfies Record<string, Example>;
`;
}

function buildStories(name, title, examples) {
  const stories = examples
    .filter(example => example.targets.includes('storybook'))
    .map(
      example =>
        `export const ${pascalCase(example.id)}: StoryObj = exampleStory(${constantName(name)}.${example.key});`
    );

  return `${TS_LICENSE_HEADER}

${GENERATED_NOTICE}

import { ${constantName(name)} } from '@clr/examples/${name}';
import { Meta, StoryObj } from '@storybook/angular';

import { exampleStoriesDecorators, exampleStoriesParameters, exampleStory } from '../../helpers/example-story';

export default {
  title: ${JSON.stringify(`${title}/Examples`)},
  decorators: exampleStoriesDecorators,
  parameters: exampleStoriesParameters,
} satisfies Meta;

${stories.join('\n\n')}
`;
}

function format(code, filePath) {
  return prettier.format(code, { ...prettierConfig, filepath: filePath });
}

function readFile(filePath) {
  return fs.existsSync(filePath) ? fs.readFileSync(filePath).toString() : undefined;
}

function stripLicenseHeader(code) {
  return code.replace(TS_LICENSE_HEADER, '').replace(HTML_LICENSE_HEADER, '').trim() + '\n';
}

function constantName(name) {
  return `${name.replaceAll('-', '_').toUpperCase()}_EXAMPLES`;
}

function camelCase(id) {
  return id.replace(/-(\w)/g, (_, letter) => letter.toUpperCase());
}

function pascalCase(id) {
  const camel = camelCase(id);
  return camel[0].toUpperCase() + camel.slice(1);
}
